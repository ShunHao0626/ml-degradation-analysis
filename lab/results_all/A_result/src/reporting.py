def generate_analysis_report(
    qc_df: pd.DataFrame,
    som_summary: dict,
    cluster_summary: pd.DataFrame,
    cluster_metrics_list: list,
    qe_sweep_df: pd.DataFrame,
    sensitivity_df: pd.DataFrame,
    kmeans_wcss_df: pd.DataFrame,
    k4_comparison: dict,
    preproc_cfg: dict,
    som_cfg: dict,
    run_start: datetime,
    packages: dict,
    out_path: Path | None = None,
) -> str:
    """Generate the full analysis report markdown."""

    n_total = len(qc_df)
    n_incl  = int((qc_df["status"] == "included").sum())
    n_excl  = n_total - n_incl

    excl_reasons = (
        qc_df[qc_df["status"] == "excluded"]
        .groupby("reason")
        .size()
        .sort_values(ascending=False)
        .head(5)
    )

    lines = [
        "# PvkSOM 200h Analysis Report",
        "",
        f"**Generated:** {datetime.now().isoformat()}",
        f"**Run start:** {run_start.isoformat()}",
        f"**Output directory:** {OUT_DATA}",
        "",
        "---",
        "",
        "## 1. Dataset Overview",
        "",
        f"| Metric | Value |",
        f"|--------|------:|<br>",
        f"| Total curves loaded | {n_total:,} |",
        f"| Included (processed) | {n_incl:,} |",
        f"| Excluded (QC failed) | {n_excl:,} |",
        f"| Time window | 0–200 h |",
        f"| Grid interval | 10 min |",
        f"| Grid points per curve | {preproc_cfg['n_time_points']} |",
        f"| savgol window | {preproc_cfg['savgol_window']} |",
        f"| savgol polyorder | {preproc_cfg['savgol_polyorder']} |",
        f"| Normalisation | Per-curve MaxAbsScaler |",
        "",
        "## 2. Inclusion and Exclusion Criteria",
        "",
        "### 2.1 Inclusion",
        "",
        "A curve is included if ALL of the following hold:",
        "- Valid curve ID, time, and PCE values",
        "- At least 10 unique time points in [0, 200h]",
        "- Max PCE > 0 in [0, 200h]",
        "- No NaN/Inf after Akima interpolation",
        "",
        "### 2.2 Exclusion",
        "",
        f"Top exclusion reasons:",
        "",
    ]

    for reason, count in excl_reasons.items():
        pct = count / n_excl * 100
        lines.append(f"- *{reason}* — {count} curves ({pct:.1f}%)")

    lines += [
        "",
        "## 3. SOM Configuration",
        "",
        f"| Parameter | Value |",
        f"|-----------|------:|<br>",
        f"| SOM shape | {som_cfg['shape'][0]}×{som_cfg['shape'][1]} |",
        f"| sigma | {som_cfg['sigma']} |",
        f"| learning_rate | {som_cfg['learning_rate']} |",
        f"| iterations | {som_cfg['iterations']:,} |",
        f"| random_seed | {som_cfg['random_seed']} |",
        f"| weight init | random_weights_init |",
        f"| activation_distance | {som_cfg['activation_distance']} |",
        f"| neighborhood_function | {som_cfg['neighborhood_function']} |",
        "",
        f"**Quantisation Error:** {som_summary.get('quantization_error', 'N/A'):.4f}",
        f"**Topographic Error:** {som_summary.get('topographic_error', 'N/A'):.4f}",
        "",
        "## 4. Cluster Results (2×2 SOM)",
        "",
    ]

    for _, row in cluster_summary.iterrows():
        lines += [
            f"### Node ({row['som_node_x']},{row['som_node_y']}) — {row['suggested_shape_name']}",
            "",
            f"| Metric | Value |",
            f"|--------|------:|<br>",
            f"| Curves | {row['n_curves']} ({row['percentage']:.1f}%) |",
            f"| PCE@0h | {row['pce_norm_t0']:.4f} |",
            f"| PCE@10h | {row['pce_norm_t10']:.4f} |",
            f"| PCE@50h | {row['pce_norm_t50']:.4f} |",
            f"| PCE@100h | {row['pce_norm_t100']:.4f} |",
            f"| PCE@150h | {row['pce_norm_t150']:.4f} |",
            f"| PCE@200h | {row['pce_norm_t200']:.4f} |",
            f"| Mean BMU distance | {row['mean_bmu_dist']:.4f} |",
            f"| AUC | {row['auc']:.4f} |",
            f"| Naming basis | {row['naming_basis']} |",
            "",
        ]

    lines += [
        "## 5. Quantisation Error Sweep (n = 2 … 10)",
        "",
        f"Main model (n=4, 2×2) QE: **{som_summary.get('quantization_error', 'N/A'):.4f}**",
        "",
        "| n | Topology | QE |",
        "|---:|:--------:|------:|<br>",
    ]

    for _, row in qe_sweep_df.iterrows():
        topo = f"{row['som_x']}×{row['som_y']}"
        star = " ← main" if row['som_x'] == 2 and row['som_y'] == 2 else ""
        lines.append(f"| {int(row['n_nodes'])} | {topo} | {row['quantization_error']:.4f}{star} |")

    lines += [
        "",
        "> ⚠️ **Topology for n ≠ 4:** 1×n rectangular (implementation assumption — not confirmed in author code).",
        "",
        "## 6. Parameter Sensitivity",
        "",
    ]

    for _, row in sensitivity_df.iterrows():
        lines.append(
            f"- **{row['sensitivity_config']}** (σ={row['som_sigma']}, lr={row['som_lr']}): "
            f"QE={row['quantization_error']:.4f}"
        )

    lines += [
        "",
        "## 7. K-means Validation (k = 2 … 10)",
        "",
        f"**SOM vs K-means(k=4):** ARI = {k4_comparison.get('ari', 'N/A'):.4f}, "
        f"NMI = {k4_comparison.get('nmi', 'N/A'):.4f}",
        "",
        "| k | WCSS |",
        "|---:|------:|<br>",
    ]

    for _, row in kmeans_wcss_df.iterrows():
        star = " ← k=4" if int(row["k"]) == 4 else ""
        lines.append(f"| {int(row['k'])} | {row['wcss']:.2f}{star} |")

    lines += [
        "",
        "## 8. Reproducibility",
        "",
        "| Package | Version |",
        "|---------|--------|<br>",
    ]

    for pkg, ver in packages.items():
        lines.append(f"| {pkg} | {ver} |")

    lines += [
        "",
        "## 9. Research Limitations",
        "",
        "1. **Pre-specified cluster count:** This analysis uses a 2×2 SOM (4 nodes) as a fixed setting. It does not prove that 4 is the optimal or only valid number of clusters for this dataset.",
        "2. **Topology assumption:** For n ≠ 4 in the QE sweep, the 1×n topology is an implementation assumption not confirmed from the author code.",
        "3. **K-means vs author DTW:** The auxiliary k-means uses Euclidean distance rather than the author's DTW metric.",
        "4. **Forward-fill for short curves:** Curves shorter than 200 h have their tails forward-filled with the last observed value. This does not extrapolate physically realistic behaviour.",
        "5. **Descriptive names are post-hoc:** Cluster shape names (stable, slow_degradation, etc.) are assigned after visual inspection of the mean curves. They are not predetermined physical categories.",
        "",
        "## 10. Suggested Next Steps",
        "",
        "1. Investigate whether Node (0,0) and (0,1) cluster curves truly represent distinct physical degradation mechanisms or are artefacts of the preprocessing pipeline.",
        "2. Cross-check with the author's original Zenodo dataset to validate preprocessing consistency.",
        "3. Explore n=5 and n=6 clusters to determine whether additional structure exists beyond the 4-node model.",
        "4. Incorporate device metadata (composition, architecture, illumination conditions) as secondary variables.",
        "",
        "---",
        "*End of analysis report.*",
    ]

    text = "\n".join(lines)
    if out_path:
        out_path.write_text(text, encoding="utf-8")
        logger.info("Saved: %s", out_path)
    return text


