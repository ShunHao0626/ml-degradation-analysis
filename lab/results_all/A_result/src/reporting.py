def generate_parameter_audit(out_path: Path | None = None) -> str:
    text = AUDIIT_MD.format(timestamp=datetime.now().isoformat())
    if out_path:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(text, encoding="utf-8")
        logger.info("Saved: %s", out_path)
    return text


